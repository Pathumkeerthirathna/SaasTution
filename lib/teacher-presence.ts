import { prisma } from "@/lib/prisma";
import { serverNow } from "@/lib/server-clock";
import { clearCancelledProvisionalFence, provisionalFenceUpdate } from "@/lib/jibri-fence-provisional";

/*
 * Teacher presence and the tab-close signal, all in the database
 * (ClassSession), so every server process and serverless instance sees the
 * same state. Every write is one conditional update (no read-then-write):
 * concurrent requests from several pages, tabs and processes cannot
 * interleave into a wrong state. Every time is the server's, on the database
 * clock (lib/server-clock.ts) unless a caller passes one: a client never
 * supplies a time (the page sends only its pageId).
 *
 * - Current page (teacherCurrentPageId): every classroom page instance
 *   registers its random pageId once, when it loads; the newest load is the
 *   current page. An older page never re-registers, so it can never take that
 *   place back (except by the handover below, when the current page closed).
 *
 * - Tab-close signal (teacherDepartureAt / teacherDeparturePageId): the
 *   CURRENT page reports `pagehide` with `persisted === false` (desktop
 *   browsers only). The browser cannot tell a closed tab from a refresh at
 *   that moment, so it is recorded as a PENDING departure. A signal from any
 *   other page (an older page's late beacon) is refused and changes nothing.
 *
 * - Reload confirmation: teacher activity in the classroom within
 *   TEACHER_DEPARTURE_CONFIRM_MS of the signal cancels it: a newly loaded page
 *   registering (a refresh, reopening the classroom), a live page's heartbeat
 *   or (re)connection (another open tab), the page coming back from the
 *   back/forward cache. Without such activity the departure is CONFIRMED once
 *   the window has passed; the first activity after it is the teacher's
 *   return (teacherActiveAfterDepartureAt) and never undoes it. The page whose
 *   activity cancelled the departure (or returned) becomes the current page:
 *   the page that signalled has gone.
 *
 * - Activity only ever comes from a live page: its own requests (register,
 *   heartbeat every TEACHER_PRESENCE_REFRESH_MS, resume, opening its
 *   live-updates connection, asking for notices). The live-updates
 *   connection's server-side timer only refreshes teacherLastSeenAt: a
 *   connection the server has not noticed is closed (a proxy, a frozen
 *   serverless function) can never cancel a departure. A missing or stale
 *   presence is NEVER taken as the teacher having left.
 */

/** How often a live classroom page sends its heartbeat (and the live-updates connection refreshes presence). */
export const TEACHER_PRESENCE_REFRESH_MS = 10_000;

/**
 * How long after a tab-close signal any teacher activity in the classroom
 * cancels it (a refresh, or reopening the classroom). Only for confirming a
 * closing signal: never a heartbeat or network timeout.
 */
export const TEACHER_DEPARTURE_CONFIRM_MS = 15_000;

/** A classroom page instance: random, generated by the page itself. */
const PAGE_ID = /^[A-Za-z0-9_-]{8,64}$/;

export function isValidPageId(value: unknown): value is string {
  return typeof value === "string" && PAGE_ID.test(value);
}

export type DepartureFields = {
  teacherDepartureAt: Date | null;
  teacherActiveAfterDepartureAt: Date | null;
};

/**
 * none: no signal. pending: signal within its window, nothing seen since.
 * cancelled: teacher activity within the window (a refresh, another tab).
 * confirmed: the window passed without activity (any later activity is the
 * teacher's return).
 */
export type DepartureState = "none" | "pending" | "cancelled" | "confirmed";

export function departureState(session: DepartureFields, now: Date): DepartureState {
  const signalAt = session.teacherDepartureAt;

  if (!signalAt) return "none";

  const deadline = signalAt.getTime() + TEACHER_DEPARTURE_CONFIRM_MS;
  const activeAt = session.teacherActiveAfterDepartureAt;

  if (activeAt && activeAt.getTime() <= deadline) return "cancelled";

  return now.getTime() <= deadline ? "pending" : "confirmed";
}

/**
 * teacherLastSeenAt only (the live-updates connection, opened and every
 * TEACHER_PRESENCE_REFRESH_MS): an active session, never moving backwards.
 * Does not touch the tab-close signal. Best effort and never throws.
 * Returns whether the row was updated.
 */
export async function recordTeacherPresence(
  sessionId: string,
  at?: Date
): Promise<boolean> {
  try {
    const seenAt = at ?? await serverNow();

    const { count } = await prisma.classSession.updateMany({
      where: {
        id: sessionId,
        isActive: true,
        OR: [{ teacherLastSeenAt: null }, { teacherLastSeenAt: { lt: seenAt } }],
      },
      data: { teacherLastSeenAt: seenAt },
    });

    return count > 0;
  } catch (error) {
    console.error("Failed to record teacher presence:", { sessionId, error });

    return false;
  }
}

/**
 * A live classroom page of the teacher (`pageId`; null: a page that did not
 * say which) was active at `seenAt`. Records presence and, if a tab-close
 * signal from ANOTHER page is waiting for its first activity, records this
 * as it (within the window: cancelled; after it: the return) and hands the
 * current page over to this one. Best effort and never throws. Returns
 * whether a departure was cancelled / returned by it.
 */
export async function recordTeacherActivity(
  sessionId: string,
  pageId: string | null,
  at?: Date
): Promise<boolean> {
  const seenAt = at ?? await serverNow();

  await recordTeacherPresence(sessionId, seenAt);

  try {
    // While no activity followed the signal, the current page IS the page
    // that signalled (only it can signal; register and this update both set
    // the activity): taking over is safe.
    const { count } = await prisma.classSession.updateMany({
      where: {
        id: sessionId,
        isActive: true,
        teacherDepartureAt: { lte: seenAt },
        teacherActiveAfterDepartureAt: null,
        ...(pageId ? { OR: [{ teacherDeparturePageId: null }, { teacherDeparturePageId: { not: pageId } }] } : {}),
      },
      data: {
        teacherActiveAfterDepartureAt: seenAt,
        ...(pageId ? { teacherCurrentPageId: pageId } : {}),
      },
    });

    // Within the window this cancelled the departure: its provisional
    // Jibri shutdown fence goes too (lib/jibri-fence-provisional.ts).
    if (count > 0) {
      await clearCancelledProvisionalFence(sessionId, s => departureState(s, seenAt) === "cancelled");
    }

    return count > 0;
  } catch (error) {
    console.error("Failed to record teacher activity:", { sessionId, error });

    return false;
  }
}

/**
 * A classroom page loaded: it becomes the current page (the newest load),
 * and its arrival is activity (a refresh cancels the old page's pending
 * signal). Sent once per page load: an older page never sends it again.
 */
export async function registerTeacherPage(
  sessionId: string,
  pageId: string,
  at?: Date
): Promise<{ registered: boolean }> {
  const now = at ?? await serverNow();

  const { count } = await prisma.classSession.updateMany({
    where: { id: sessionId, isActive: true },
    data: { teacherCurrentPageId: pageId },
  });

  if (count > 0) {
    await recordTeacherActivity(sessionId, pageId, now);
  }

  return { registered: count > 0 };
}

export type DepartureSignalResult =
  /** Recorded as a pending departure. */
  | { accepted: true }
  /**
   * duplicate: this page's signal is already waiting.
   * stale-page: not the current page (an older page, a superseded tab, a
   * page that never registered): it cannot start a departure.
   * session-not-active: the session ended (or does not exist).
   */
  | { accepted: false; reason: "duplicate" | "stale-page" | "session-not-active" };

/**
 * The classroom page `pageId` reports it is closing (pagehide, not
 * persisted). Ownership is checked by the caller. Accepted only from the
 * current page, and not again while its own signal is still waiting.
 */
export async function recordTeacherDepartureSignal(
  sessionId: string,
  pageId: string,
  at?: Date
): Promise<DepartureSignalResult> {
  const now = at ?? await serverNow();

  const signal = (fence: { expect: Record<string, unknown>; data: Record<string, unknown> } | null) =>
    prisma.classSession.updateMany({
      where: {
        id: sessionId,
        isActive: true,
        teacherCurrentPageId: pageId,
        OR: [
          { teacherDeparturePageId: null },
          { teacherDeparturePageId: { not: pageId } },
          // Its earlier signal was answered (a bfcache return after the window).
          { teacherActiveAfterDepartureAt: { not: null } },
        ],
        // The fence state the fence data was computed from.
        ...(fence ? fence.expect : {}),
      },
      data: {
        teacherDepartureAt: now,
        teacherDeparturePageId: pageId,
        teacherActiveAfterDepartureAt: null,
        // The provisional Jibri shutdown fence, in this same update.
        ...(fence ? fence.data : {}),
      },
    });

  // The fence part never blocks the signal: if it cannot be computed (or the
  // fence changed meanwhile, twice), the signal is recorded without it and
  // the departure stop arms the fence later (lib/jibri-shutdown-gate.ts).
  const fenceFor = async () => {
    try {
      return await provisionalFenceUpdate(sessionId, now, s => departureState(s, now) === "confirmed");
    } catch (error) {
      console.error("Could not prepare the provisional Jibri shutdown fence:", { sessionId, error });
      return null;
    }
  };

  let fence = await fenceFor();
  let { count } = await signal(fence);

  for (let retry = 0; count === 0 && fence && retry < 2; retry++) {
    fence = retry === 0 ? await fenceFor() : null;
    ({ count } = await signal(fence));
  }

  if (count > 0) {
    return { accepted: true };
  }

  const session = await prisma.classSession.findUnique({
    where: { id: sessionId },
    select: { isActive: true, teacherCurrentPageId: true },
  });

  if (!session?.isActive) {
    return { accepted: false, reason: "session-not-active" };
  }

  return { accepted: false, reason: session.teacherCurrentPageId === pageId ? "duplicate" : "stale-page" };
}

export type ResumeSignalResult = { cancelled: boolean; returned: boolean };

/**
 * A page came back from the back/forward cache (pageshow, persisted). If its
 * own signal is still within the window, the signal is withdrawn entirely (it
 * stays the current page and may signal again later). Otherwise it is a live
 * page's activity like any other.
 */
export async function recordTeacherResumeSignal(
  sessionId: string,
  pageId: string,
  at?: Date
): Promise<ResumeSignalResult> {
  const now = at ?? await serverNow();

  const withdrawn = await prisma.classSession.updateMany({
    where: {
      id: sessionId,
      isActive: true,
      teacherCurrentPageId: pageId,
      teacherDeparturePageId: pageId,
      teacherActiveAfterDepartureAt: null,
      teacherDepartureAt: { gte: new Date(now.getTime() - TEACHER_DEPARTURE_CONFIRM_MS) },
    },
    data: { teacherDepartureAt: null, teacherDeparturePageId: null, teacherActiveAfterDepartureAt: null },
  });

  if (withdrawn.count > 0) {
    await clearCancelledProvisionalFence(sessionId, () => true);
    await recordTeacherPresence(sessionId, now);
    return { cancelled: true, returned: false };
  }

  // Its own signal, answered by nobody else: after the window this is the return.
  const returned = await prisma.classSession.updateMany({
    where: {
      id: sessionId,
      isActive: true,
      teacherDeparturePageId: pageId,
      teacherActiveAfterDepartureAt: null,
      teacherDepartureAt: { lte: now },
    },
    data: { teacherActiveAfterDepartureAt: now },
  });

  if (returned.count === 0) {
    await recordTeacherActivity(sessionId, pageId, now);
  } else {
    await recordTeacherPresence(sessionId, now);
  }

  return { cancelled: false, returned: returned.count > 0 };
}
