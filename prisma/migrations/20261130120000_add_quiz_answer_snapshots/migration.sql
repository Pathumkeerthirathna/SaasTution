-- ---------------------------------------------------------------------------
-- Quiz answer snapshots: protect historical quiz attempts from quiz edits.
--
-- Editing a quiz replaces all of its questions and options
-- (services/lecture-service.ts updateQuizForTeacher). Until now every
-- QuizSubmissionAnswer referenced its question with ON DELETE CASCADE, so an
-- edit silently deleted every student's submitted answers while their
-- QuizSubmission score / attempt count stayed, and the review showed the NEW
-- questions against the OLD score.
--
-- After this migration each answer row is an immutable record of what was
-- answered:
--  - "questionText", "questionOrderIndex", "answerType", "optionsSnapshot"
--    ([{ id, text, isCorrect, orderIndex }], lib/quiz-answer-snapshot.ts):
--    written with every new answer;
--  - "questionId" becomes NULLABLE and its foreign key ON DELETE SET NULL:
--    replacing a question keeps the answer (and its snapshot).
--
-- BACKFILL (exact, not approximate): every answer that still exists was
-- written after the latest edit of its quiz (an edit deleted all earlier
-- answers through the old cascade), so its question and options are still the
-- ones that were answered; their ids are the ones in "selectedOptionIds".
-- Answers deleted by earlier edits cannot be recovered (their scores remain).
--
-- Order: add the columns as NULLable, backfill, then SET NOT NULL (fails, and
-- rolls the migration back, if any row could not be backfilled), then swap
-- the foreign key. The NOT NULL / FK statements are those generated by
-- `prisma migrate diff`; the staging and the backfill are hand-written.
--
-- Deploy order: after 20261129120000_add_lecture_is_default and BEFORE the
-- code that writes or reads the snapshot columns (the quiz submit and review
-- routes, lib/quiz-answer-snapshot.ts).
-- Guarded by tests/quizzes/quiz-answer-snapshots-migration-guard.test.cjs.
-- ---------------------------------------------------------------------------

-- MANUAL: fail instead of waiting indefinitely for a lock on the quiz tables.
-- Session-level SET (not SET LOCAL), as the earlier migrations; RESET at the end.
SET lock_timeout = '5s';

-- MANUAL: the snapshot columns, NULLable until backfilled.
ALTER TABLE "QuizSubmissionAnswer" ADD COLUMN "answerType" "QuizAnswerType",
ADD COLUMN "optionsSnapshot" JSONB,
ADD COLUMN "questionOrderIndex" INTEGER,
ADD COLUMN "questionText" TEXT;

-- MANUAL: backfill every existing answer from its (still current) question and options.
UPDATE "QuizSubmissionAnswer" AS a
SET "questionText" = q."text",
    "questionOrderIndex" = q."orderIndex",
    "answerType" = q."answerType",
    "optionsSnapshot" = COALESCE(
      (
        SELECT jsonb_agg(
                 jsonb_build_object('id', o."id", 'text', o."text", 'isCorrect', o."isCorrect", 'orderIndex', o."orderIndex")
                 ORDER BY o."orderIndex", o."id"
               )
        FROM "QuizQuestionOption" AS o
        WHERE o."questionId" = q."id"
      ),
      '[]'::jsonb
    )
FROM "QuizQuestion" AS q
WHERE q."id" = a."questionId";

-- AlterTable (generated): every snapshot column is required from now on.
ALTER TABLE "QuizSubmissionAnswer" ALTER COLUMN "answerType" SET NOT NULL,
ALTER COLUMN "optionsSnapshot" SET NOT NULL,
ALTER COLUMN "questionOrderIndex" SET NOT NULL,
ALTER COLUMN "questionText" SET NOT NULL,
ALTER COLUMN "questionId" DROP NOT NULL;

-- DropForeignKey (generated)
ALTER TABLE "QuizSubmissionAnswer" DROP CONSTRAINT "QuizSubmissionAnswer_questionId_fkey";

-- AddForeignKey (generated): replacing a question keeps its answers.
ALTER TABLE "QuizSubmissionAnswer" ADD CONSTRAINT "QuizSubmissionAnswer_questionId_fkey" FOREIGN KEY ("questionId") REFERENCES "QuizQuestion"("id") ON DELETE SET NULL ON UPDATE CASCADE;

RESET lock_timeout;
