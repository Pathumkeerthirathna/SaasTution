-- ---------------------------------------------------------------------------
-- Student QR identity tokens (see docs/student-qr-identity.md).
--
-- Additive only: one enum, one table, its indexes and constraints. No existing
-- table, column, row or migration is changed; nothing is backfilled (tokens
-- are issued lazily, on a student's first QR view).
--
-- The QR token itself is NEVER stored: it is derived on demand from
-- STUDENT_QR_SECRET, the row id and "nonce"; only its SHA-256 hash is kept in
-- "tokenHash" for lookups. "createdAt" / "revokedAt" have no database default:
-- the application writes them as real UTC instants.
--
-- Parts marked MANUAL are not generated by Prisma (CHECK constraints and the
-- partial unique index). Prisma 5.22 cannot express partial indexes, so a
-- later `prisma migrate dev` may report the index as drift: never accept a
-- generated DROP INDEX for it. Guarded by
-- tests/student-qr/student-qr-migration-guard.test.cjs.
-- ---------------------------------------------------------------------------

-- CreateEnum
CREATE TYPE "StudentQrTokenReason" AS ENUM ('ISSUE', 'REGENERATE', 'SYSTEM_REISSUE');

-- CreateTable
CREATE TABLE "StudentQrToken" (
    "id" TEXT NOT NULL,
    "studentId" TEXT NOT NULL,
    "nonce" TEXT NOT NULL,
    "tokenHash" TEXT NOT NULL,
    "reason" "StudentQrTokenReason" NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL,
    "createdByRole" TEXT NOT NULL,
    "createdById" TEXT,
    "revokedAt" TIMESTAMP(3),
    "revokedByRole" TEXT,
    "revokedById" TEXT,
    "revokedReason" TEXT,

    CONSTRAINT "StudentQrToken_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE UNIQUE INDEX "StudentQrToken_tokenHash_key" ON "StudentQrToken"("tokenHash");

-- CreateIndex
CREATE INDEX "StudentQrToken_studentId_createdAt_idx" ON "StudentQrToken"("studentId", "createdAt");

-- CreateIndex
CREATE INDEX "StudentQrToken_studentId_revokedAt_idx" ON "StudentQrToken"("studentId", "revokedAt");

-- AddForeignKey
ALTER TABLE "StudentQrToken" ADD CONSTRAINT "StudentQrToken_studentId_fkey" FOREIGN KEY ("studentId") REFERENCES "Student"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- MANUAL: value constraints (the service validates too).
-- Who created the row; a STUDENT / TEACHER row always names its creator.
ALTER TABLE "StudentQrToken" ADD CONSTRAINT "StudentQrToken_createdByRole_check"
  CHECK ("createdByRole" IN ('STUDENT', 'TEACHER', 'SYSTEM'));
ALTER TABLE "StudentQrToken" ADD CONSTRAINT "StudentQrToken_createdById_check"
  CHECK ("createdByRole" = 'SYSTEM' OR "createdById" IS NOT NULL);
-- 32 random bytes as base64url (43 characters, no padding).
ALTER TABLE "StudentQrToken" ADD CONSTRAINT "StudentQrToken_nonce_check"
  CHECK ("nonce" ~ '^[A-Za-z0-9_-]{43}$');
-- SHA-256 hex digest; also rules out storing a raw token here by mistake.
ALTER TABLE "StudentQrToken" ADD CONSTRAINT "StudentQrToken_tokenHash_check"
  CHECK ("tokenHash" ~ '^[0-9a-f]{64}$');
ALTER TABLE "StudentQrToken" ADD CONSTRAINT "StudentQrToken_revokedAt_check"
  CHECK ("revokedAt" IS NULL OR "revokedAt" >= "createdAt");
-- Revocation audit: an active token has no revocation fields at all; a revoked
-- token always records who revoked it (role, and id unless SYSTEM) and why.
ALTER TABLE "StudentQrToken" ADD CONSTRAINT "StudentQrToken_revokedByRole_check"
  CHECK ("revokedByRole" IS NULL OR "revokedByRole" IN ('STUDENT', 'TEACHER', 'SYSTEM'));
ALTER TABLE "StudentQrToken" ADD CONSTRAINT "StudentQrToken_revokedReason_check"
  CHECK ("revokedReason" IS NULL OR "revokedReason" IN ('REGENERATE', 'SYSTEM_REISSUE'));
ALTER TABLE "StudentQrToken" ADD CONSTRAINT "StudentQrToken_revocation_audit_check"
  CHECK (
    ("revokedAt" IS NULL AND "revokedByRole" IS NULL AND "revokedById" IS NULL AND "revokedReason" IS NULL)
    OR ("revokedAt" IS NOT NULL AND "revokedByRole" IS NOT NULL AND "revokedReason" IS NOT NULL
        AND ("revokedByRole" = 'SYSTEM' OR "revokedById" IS NOT NULL)
        AND (("revokedReason" = 'SYSTEM_REISSUE') = ("revokedByRole" = 'SYSTEM')))
  );

-- MANUAL: at most ONE active (not revoked) token per student. Concurrent
-- first issues and regenerations cannot leave two active tokens.
CREATE UNIQUE INDEX "StudentQrToken_one_active_per_student"
  ON "StudentQrToken" ("studentId")
  WHERE "revokedAt" IS NULL;
