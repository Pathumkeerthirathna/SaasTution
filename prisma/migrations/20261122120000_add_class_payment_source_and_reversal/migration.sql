-- Hand-written: a student slip never carries the teacher-recording fields; a
-- teacher-recorded payment is always CONFIRMED, positive, with a method and
-- the date received. (recordedByTeacherId may become NULL only through the
-- teacher's deletion, ON DELETE SET NULL.)
ALTER TABLE "ClassPayment" ADD CONSTRAINT "ClassPayment_source_fields_check"
  CHECK (
    ("source" = 'STUDENT_SLIP' AND "paymentMethod" IS NULL AND "receivedAt" IS NULL AND "recordedByTeacherId" IS NULL)
    OR ("source" = 'TEACHER_RECORDED' AND "paymentMethod" IS NOT NULL AND "receivedAt" IS NOT NULL AND "status" = 'CONFIRMED' AND "amount" > 0)
  );

-- Hand-written: a request key is never an empty string.
ALTER TABLE "ClassPayment" ADD CONSTRAINT "ClassPayment_requestKey_check"
  CHECK ("requestKey" IS NULL OR length("requestKey") BETWEEN 8 AND 100);

-- Hand-written: a reversal is a positive amount with a reason.
ALTER TABLE "ClassPaymentReversal" ADD CONSTRAINT "ClassPaymentReversal_amount_check"
  CHECK ("amount" > 0);
ALTER TABLE "ClassPaymentReversal" ADD CONSTRAINT "ClassPaymentReversal_reason_check"
  CHECK (length(btrim("reason")) BETWEEN 3 AND 500);

