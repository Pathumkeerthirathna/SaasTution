-- ---------------------------------------------------------------------------
-- Student confirmation history (see docs/student-confirmation-history.md).
--
-- Additive only: one enum, one table, its index, foreign keys, constraints and
-- an append-only trigger. No existing table, column, row or migration is
-- changed. Nothing is backfilled: decisions made before this migration have no
-- history rows (approvalDuring in lib/student-confirmation-history.ts reports
-- the time before them as UNKNOWN).
--
-- "decidedAt" / "previousConfirmedAt" have no database default: the
-- application writes real UTC instants (new Date()), never now().
--
-- Parts marked MANUAL are not generated by Prisma (CHECK constraints, the
-- trigger and its function). Prisma ignores them, so they are never reported
-- as drift and `prisma db push` would NOT create them: apply this migration
-- with `prisma migrate deploy` only. Guarded by
-- tests/students/confirmation-history-migration-guard.test.cjs.
-- ---------------------------------------------------------------------------

-- CreateEnum
CREATE TYPE "StudentConfirmationSource" AS ENUM ('INDIVIDUAL', 'BULK');

-- CreateTable
CREATE TABLE "StudentConfirmationHistory" (
    "id" TEXT NOT NULL,
    "studentId" TEXT NOT NULL,
    "fromStatus" "StudentConfirmationStatus" NOT NULL,
    "toStatus" "StudentConfirmationStatus" NOT NULL,
    "decidedAt" TIMESTAMP(3) NOT NULL,
    "previousConfirmedAt" TIMESTAMP(3),
    "decidedByTeacherId" TEXT NOT NULL,
    "source" "StudentConfirmationSource" NOT NULL,
    "batchId" TEXT,

    CONSTRAINT "StudentConfirmationHistory_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE INDEX "StudentConfirmationHistory_studentId_decidedAt_idx" ON "StudentConfirmationHistory"("studentId", "decidedAt");

-- AddForeignKey
ALTER TABLE "StudentConfirmationHistory" ADD CONSTRAINT "StudentConfirmationHistory_studentId_fkey" FOREIGN KEY ("studentId") REFERENCES "Student"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- AddForeignKey
ALTER TABLE "StudentConfirmationHistory" ADD CONSTRAINT "StudentConfirmationHistory_decidedByTeacherId_fkey" FOREIGN KEY ("decidedByTeacherId") REFERENCES "Teacher"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- MANUAL: value constraints (the service enforces the same rules).
-- A row is a real change of status, and no decision ever returns to PENDING.
ALTER TABLE "StudentConfirmationHistory" ADD CONSTRAINT "StudentConfirmationHistory_status_change_check"
  CHECK ("fromStatus" <> "toStatus");
ALTER TABLE "StudentConfirmationHistory" ADD CONSTRAINT "StudentConfirmationHistory_toStatus_check"
  CHECK ("toStatus" <> 'PENDING');
-- A bulk approval always has a batch id; an individual decision never does.
ALTER TABLE "StudentConfirmationHistory" ADD CONSTRAINT "StudentConfirmationHistory_batch_check"
  CHECK (("source" = 'BULK') = ("batchId" IS NOT NULL));
-- A bulk approval only ever approves pending students.
ALTER TABLE "StudentConfirmationHistory" ADD CONSTRAINT "StudentConfirmationHistory_bulk_transition_check"
  CHECK ("source" <> 'BULK' OR ("fromStatus" = 'PENDING' AND "toStatus" = 'APPROVED'));
-- Decisions on a student are strictly ordered in time.
ALTER TABLE "StudentConfirmationHistory" ADD CONSTRAINT "StudentConfirmationHistory_order_check"
  CHECK ("previousConfirmedAt" IS NULL OR "previousConfirmedAt" < "decidedAt");

-- MANUAL: append-only. Rows can be inserted, never changed or removed.
CREATE FUNCTION "StudentConfirmationHistory_append_only"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'StudentConfirmationHistory is append-only (% refused)', TG_OP;
END;
$$;

CREATE TRIGGER "StudentConfirmationHistory_no_update_delete"
  BEFORE UPDATE OR DELETE ON "StudentConfirmationHistory"
  FOR EACH ROW EXECUTE FUNCTION "StudentConfirmationHistory_append_only"();

CREATE TRIGGER "StudentConfirmationHistory_no_truncate"
  BEFORE TRUNCATE ON "StudentConfirmationHistory"
  FOR EACH STATEMENT EXECUTE FUNCTION "StudentConfirmationHistory_append_only"();
