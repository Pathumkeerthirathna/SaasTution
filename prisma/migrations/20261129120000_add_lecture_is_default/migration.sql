-- ---------------------------------------------------------------------------
-- Default lecture (lib/default-lecture.ts): every class gets one internal
-- lecture, created with the class, that holds class-level content (the
-- upcoming Notes module) and is never a teaching session.
--
-- ADDITIVE ONLY:
--  - "Lecture"."isDefault" BOOLEAN NOT NULL DEFAULT false: every existing and
--    every normally created lecture is a normal lecture. (A constant default:
--    a catalog-only change on PostgreSQL 11+, no table rewrite.)
--  - partial unique index "Lecture_one_default_per_class": at most one
--    default lecture per class (Prisma 5.22 cannot declare partial indexes;
--    hand-written, mirrored by the comment on Lecture.isDefault in
--    schema.prisma).
-- NO BACKFILL: existing classes get their default lecture from a separate,
-- reviewed manual SQL script after deployment (docs/default-lecture.md).
-- The ADD COLUMN is generated by `prisma migrate diff`; the index and the
-- lock timeout are hand-written.
--
-- Deploy order: after 20261128120000_add_resource_month_access and BEFORE the
-- code that reads or writes "Lecture"."isDefault".
-- Guarded by tests/lectures/default-lecture-migration-guard.test.cjs.
-- ---------------------------------------------------------------------------

-- MANUAL: fail instead of waiting indefinitely for a lock on "Lecture".
-- Session-level SET (not SET LOCAL): it works whether Prisma runs this script
-- as one implicit transaction or statement by statement. RESET at the end
-- restores the default. See docs/lecture-attendance.md ("Lock timeout").
SET lock_timeout = '5s';

-- AlterTable
ALTER TABLE "Lecture" ADD COLUMN "isDefault" BOOLEAN NOT NULL DEFAULT false;

-- MANUAL: at most one default lecture per class (only rows with
-- "isDefault" = true are indexed; normal lectures are unaffected).
CREATE UNIQUE INDEX "Lecture_one_default_per_class" ON "Lecture" ("classId") WHERE "isDefault" = true;

RESET lock_timeout;
